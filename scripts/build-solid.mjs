// Bundles crates/corten/js/solid.js (Solid + mount) into crates/corten/js/dist/solid.js, which
// the corten crate embeds. "corten" stays an import, resolved by the page's import map.
import { build } from "esbuild";
import { readFileSync, statSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const js = join(root, "crates", "corten", "js");
const out = join(js, "dist", "solid.js");
const solid = JSON.parse(readFileSync(join(root, "node_modules", "solid-js", "package.json"), "utf8"));
await build({
  entryPoints: [join(js, "solid.js")],
  outfile: out,
  bundle: true,
  format: "esm",
  minify: true,
  target: "es2022",
  external: ["corten"],
  conditions: ["browser"],
  legalComments: "none",
  banner: { js: `// Solid ${solid.version} (MIT, Ryan Carniato) + corten/solid. Generated by scripts/build-solid.mjs; do not edit.` },
});
console.log(`${out}: ${statSync(out).size} B, ${gzipSync(readFileSync(out)).length} B gzip`);
